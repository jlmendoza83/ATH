#!/usr/bin/env python3
"""
tools/tts.py — Voice-over + timing map for the explainer video.

Reads script.json, synthesises every segment with Kokoro (offline TTS),
lays the segments out on a single timeline and writes:

  build/narration.wav     full-length voice track (24 kHz mono)
  src/timings.js          window.TIMINGS used by src/index.html to sync animation
  dist/captions-en.vtt    WebVTT captions for the <video> element

Segments are cached in build/tts-cache, so editing one line only re-renders that line.
"""

import hashlib
import json
import os
import pathlib
import re
import urllib.request

import numpy as np
import soundfile as sf

ROOT   = pathlib.Path(__file__).resolve().parent.parent
BUILD  = ROOT / "build"
CACHE  = BUILD / "tts-cache"
MODELS = pathlib.Path(os.environ.get("KOKORO_DIR", BUILD / "models"))
SR     = 24000

MODEL_URLS = {
    "kokoro-v1.0.int8.onnx": "https://github.com/thewh1teagle/kokoro-onnx/releases/download/model-files-v1.0/kokoro-v1.0.int8.onnx",
    "voices-v1.0.bin":       "https://github.com/thewh1teagle/kokoro-onnx/releases/download/model-files-v1.0/voices-v1.0.bin",
}


def ensure_models():
    MODELS.mkdir(parents=True, exist_ok=True)
    for name, url in MODEL_URLS.items():
        dest = MODELS / name
        if not dest.exists():
            print(f"[tts] downloading {name} …")
            urllib.request.urlretrieve(url, dest)


def trim(samples, threshold=0.004, margin=0.04):
    """Cut leading/trailing silence, keeping a small natural margin."""
    loud = np.where(np.abs(samples) > threshold)[0]
    if len(loud) == 0:
        return samples
    pad = int(margin * SR)
    return samples[max(0, loud[0] - pad): min(len(samples), loud[-1] + pad)]


def synth(kokoro, text, voice, speed, lang):
    key = hashlib.sha1(f"{voice}|{speed}|{lang}|{text}".encode()).hexdigest()[:16]
    path = CACHE / f"{key}.wav"
    if path.exists():
        samples, _ = sf.read(path, dtype="float32")
        return samples
    samples, sr = kokoro.create(text, voice=voice, speed=speed, lang=lang)
    assert sr == SR, sr
    samples = trim(np.asarray(samples, dtype="float32"))
    sf.write(path, samples, SR)
    return samples


def write_if_changed(path, text):
    """Keep mtimes stable so build.sh only re-renders the video when timings really change."""
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def vtt_time(t):
    h, rem = divmod(t, 3600)
    m, s = divmod(rem, 60)
    return f"{int(h):02d}:{int(m):02d}:{s:06.3f}"


def caption_chunks(text, max_len=78):
    """Split a sentence into caption-sized chunks at natural breaks."""
    words, chunks, cur = text.split(), [], ""
    for w in words:
        if cur and len(cur) + 1 + len(w) > max_len:
            chunks.append(cur)
            cur = w
        else:
            cur = f"{cur} {w}".strip()
        if re.search(r"[.:;?!]$", w) and len(cur) > max_len * 0.45:
            chunks.append(cur)
            cur = ""
    if cur:
        chunks.append(cur)
    return chunks


def main():
    script = json.loads((ROOT / "script.json").read_text())
    defaults = script["defaults"]
    CACHE.mkdir(parents=True, exist_ok=True)
    ensure_models()

    from kokoro_onnx import Kokoro
    kokoro = Kokoro(str(MODELS / "kokoro-v1.0.int8.onnx"), str(MODELS / "voices-v1.0.bin"))

    timings = {"scenes": {}, "segments": {}, "order": []}
    placed = []          # (start_time, samples)
    t = 0.0

    for scene in script["scenes"]:
        scene_start = t
        t += scene.get("pad_before", defaults["pad_before"])
        for i, seg in enumerate(scene["segments"]):
            if i > 0:
                t += seg.get("gap", defaults["gap"])
            samples = synth(kokoro, seg["text"], script["voice"], script["speed"], script["lang"])
            dur = len(samples) / SR
            placed.append((t, samples))
            timings["segments"][seg["id"]] = {
                "start": round(t, 3), "end": round(t + dur, 3),
                "text": seg["text"], "scene": scene["id"],
            }
            print(f"[tts] {seg['id']:<8} {t:7.2f}s  +{dur:5.2f}s")
            t += dur
        t += scene.get("pad_after", defaults["pad_after"])
        timings["scenes"][scene["id"]] = {"start": round(scene_start, 3), "end": round(t, 3)}
        timings["order"].append(scene["id"])

    timings["duration"] = round(t, 3)

    track = np.zeros(int(np.ceil(t * SR)) + SR, dtype="float32")
    for start, samples in placed:
        i = int(round(start * SR))
        track[i:i + len(samples)] += samples
    track = track[: int(np.ceil(t * SR))]
    sf.write(BUILD / "narration.wav", track, SR, subtype="PCM_16")

    write_if_changed(BUILD / "timings.json", json.dumps(timings, indent=1))
    write_if_changed(ROOT / "src" / "timings.js",
        "// Generated by tools/tts.py — do not edit by hand.\n"
        f"window.TIMINGS = {json.dumps(timings, indent=1)};\n"
    )

    lines = ["WEBVTT", ""]
    n = 1
    for seg in timings["segments"].values():
        chunks = caption_chunks(seg["text"])
        total_chars = sum(len(c) for c in chunks)
        cur = seg["start"]
        for c in chunks:
            end = cur + (seg["end"] - seg["start"]) * len(c) / total_chars
            lines += [str(n), f"{vtt_time(cur)} --> {vtt_time(end)}", c, ""]
            n += 1
            cur = end
    (ROOT / "dist").mkdir(exist_ok=True)
    write_if_changed(ROOT / "dist" / "captions-en.vtt", "\n".join(lines))

    print(f"[tts] total duration {t:.2f}s")


if __name__ == "__main__":
    main()
